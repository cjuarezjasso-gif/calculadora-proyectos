-- 1. CREAR LA TABLA DE USUARIOS
CREATE TABLE usuarios (
  id_usuario NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR2(100) NOT NULL,
  correo VARCHAR2(100) UNIQUE NOT NULL,
  password VARCHAR2(255) NOT NULL,
  fecha_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. AGREGAR LA COLUMNA A LA TABLA PROYECTOS
ALTER TABLE proyectos ADD fk_id_usuario NUMBER;

-- 3. CONECTAR LOS PROYECTOS CON EL USUARIO (LLAVE FORÁNEA)
ALTER TABLE proyectos ADD CONSTRAINT fk_proyecto_usuario FOREIGN KEY (fk_id_usuario) REFERENCES usuarios(id_usuario) ON DELETE CASCADE;